"""
app/services/youtube.py
────────────────────────
YouTube Data API v3 integration.

Searches for repair/tutorial videos and caches results in PostgreSQL
to preserve the daily API quota (10,000 units/day; search costs ~100 units).
Cache TTL: 7 days.
"""

import html
import logging
from datetime import datetime, timedelta, timezone
from typing import Any

from googleapiclient.discovery import build
from googleapiclient.errors import HttpError
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.config import settings
from app.models.spare_part import YouTubeCache

logger = logging.getLogger(__name__)

_CACHE_TTL_DAYS = 7
_YOUTUBE_SERVICE_NAME = "youtube"
_YOUTUBE_VERSION = "v3"

_LANG_CODES: dict[str, str] = {
    "malayalam": "ml",
    "hindi": "hi",
    "english": "en",
    "tamil": "ta",
    "telugu": "te",
    "kannada": "kn",
    "marathi": "mr",
    "bengali": "bn",
}


def _build_youtube_client():
    """Build a YouTube Data API client (synchronous, used in thread pool)."""
    return build(
        _YOUTUBE_SERVICE_NAME,
        _YOUTUBE_VERSION,
        developerKey=settings.youtube_api_key,
        cache_discovery=False,
    )


def _search_youtube_sync(query: str, max_results: int, language: str | None = None) -> list[dict[str, str]]:
    """
    Perform a synchronous YouTube search.
    Run this in a thread pool (via asyncio.to_thread) to avoid blocking the event loop.
    """
    lang_lower = (language or "").strip().lower()
    lang_code = _LANG_CODES.get(lang_lower, "en")

    # If language is provided and not already in the query, enhance it
    search_q = query
    if lang_lower and lang_lower not in query.lower():
        search_q = f"{query} {lang_lower}"

    youtube = _build_youtube_client()
    request = youtube.search().list(
        part="snippet",
        q=search_q,
        type="video",
        maxResults=max_results,
        relevanceLanguage=lang_code,
        safeSearch="moderate",
        videoDuration="medium",       # 4–20 min — typical tutorial length
        videoEmbeddable="true",
    )
    response = request.execute()

    results = []
    for item in response.get("items", []):
        snippet = item.get("snippet", {})
        video_id = item.get("id", {}).get("videoId", "")
        clean_title = html.unescape(snippet.get("title", "Tutorial"))
        channel_name = html.unescape(snippet.get("channelTitle", ""))
        results.append(
            {
                "title": clean_title,
                "channel": channel_name,
                "thumbnail": snippet.get("thumbnails", {}).get("default", {}).get("url", ""),
                "url": f"https://youtu.be/{video_id}",
                "video_id": video_id,
            }
        )
    return results


async def search_videos(
    query: str,
    db: AsyncSession,
    max_results: int | None = None,
    language: str | None = None,
) -> list[dict[str, str]]:
    """
    Search YouTube for repair tutorial videos, with DB caching.

    Args:
        query:       The search string (generated by AI engine).
        db:          Async DB session (for cache read/write).
        max_results: Number of videos to return (defaults to settings value).
        language:    Optional preferred language (e.g. 'malayalam', 'english', 'hindi').

    Returns:
        List of dicts with 'title', 'url', 'channel', 'thumbnail', 'video_id'.
    """
    if max_results is None:
        max_results = settings.youtube_max_results

    now = datetime.now(tz=timezone.utc)
    lang_tag = (language or "default").strip().lower()
    cache_key = f"{query.lower().strip()}::{lang_tag}"

    # ── Check cache ───────────────────────────────────────────
    stmt = select(YouTubeCache).where(YouTubeCache.query == cache_key)
    result = await db.execute(stmt)
    cached: YouTubeCache | None = result.scalar_one_or_none()

    if cached and (cached.expires_at is None or cached.expires_at > now):
        logger.info("YouTube cache HIT for query: %r (lang: %s)", query, lang_tag)
        cached.hit_count += 1
        return cached.results[:max_results]

    # ── Call YouTube API ──────────────────────────────────────
    logger.info("YouTube cache MISS — calling API for query: %r (lang: %s)", query, lang_tag)
    try:
        import asyncio
        videos = await asyncio.to_thread(_search_youtube_sync, query, max_results, language)
    except HttpError as exc:
        logger.error("YouTube API HTTP error for query %r: %s", query, exc)
        return []
    except Exception as exc:
        logger.error("Unexpected error searching YouTube for %r: %s", query, exc)
        return []

    # ── Update / insert cache ─────────────────────────────────
    expires_at = now + timedelta(days=_CACHE_TTL_DAYS)
    if cached:
        cached.results = videos
        cached.expires_at = expires_at
        cached.hit_count += 1
    else:
        db.add(
            YouTubeCache(
                query=cache_key,
                results=videos,
                expires_at=expires_at,
            )
        )

    await db.flush()
    return videos


async def search_multiple_queries(
    queries: list[str],
    db: AsyncSession,
    videos_per_query: int = 2,
    language: str | None = None,
) -> list[dict[str, str]]:
    """
    Search YouTube for multiple queries and deduplicate results.
    Useful when the AI engine returns several search queries.
    Limited to 3 queries max to protect quota.
    """
    seen_ids: set[str] = set()
    all_videos: list[dict[str, str]] = []

    for query in queries[:3]:
        videos = await search_videos(query, db, max_results=videos_per_query, language=language)
        for v in videos:
            vid_id = v.get("video_id", v.get("url", ""))
            if vid_id not in seen_ids:
                seen_ids.add(vid_id)
                all_videos.append(v)

    return all_videos


def format_videos_for_whatsapp(videos: list[dict[str, Any]], language: str | None = None) -> str:
    """Format video list as a plain-text WhatsApp message block."""
    if not videos:
        lang_str = f" in {language.capitalize()}" if language else ""
        return f"_No tutorial videos found{lang_str} for this repair._"
    lines = []
    for v in videos:
        lines.append(f"▶️ *{v.get('title', 'Tutorial')}*")
        lines.append(f"   📺 {v.get('channel', '')}")
        lines.append(f"   🔗 {v.get('url', '')}")
    return "\n".join(lines)
